import AppKit
import CryptoKit

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, link, image, file, color }

    let id: UUID
    var kind: Kind
    var text: String?
    /// PNG file name inside the clipboard image folder.
    var imageFile: String?
    var filePaths: [String]?
    var date: Date
    var sourceApp: String?
    var sourceBundle: String?
    var pinned: Bool
    var hash: String
    var imageSize: CGSize?

    var title: String {
        switch kind {
        case .image:
            if let imageSize { return "Image (\(Int(imageSize.width))×\(Int(imageSize.height)))" }
            return "Image"
        case .file:
            let names = (filePaths ?? []).map { ($0 as NSString).lastPathComponent }
            return names.count > 1 ? "\(names[0]) + \(names.count - 1) more" : names.first ?? "File"
        default:
            let firstLine = (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
                .split(separator: "\n", maxSplits: 1, omittingEmptySubsequences: true).first.map(String.init) ?? ""
            return String(firstLine.prefix(200))
        }
    }
}

/// Watches the general pasteboard and keeps a persistent history, Raycast-style.
final class ClipboardStore {
    private(set) var items: [ClipItem] = []
    var onChange: (() -> Void)?
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let limit = 500
    private let folder: URL
    let imageFolder: URL
    private var historyFile: URL { folder.appendingPathComponent("clipboard.json") }

    /// Types published by password managers and other apps that ask not to be recorded.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]

    init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        folder = support.appendingPathComponent("Prism", isDirectory: true)
        imageFolder = folder.appendingPathComponent("clipboard-images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imageFolder, withIntermediateDirectories: true)
        load()
    }

    var paused: Bool {
        get { UserDefaults.standard.bool(forKey: DefaultsKey.clipboardPaused) }
        set { UserDefaults.standard.set(newValue, forKey: DefaultsKey.clipboardPaused) }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.1
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard !paused else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        guard let item = capture(pasteboard, app: front) else { return }
        insert(item)
    }

    private func capture(_ pasteboard: NSPasteboard, app: NSRunningApplication?) -> ClipItem? {
        let base = { (kind: ClipItem.Kind, hash: String) in
            ClipItem(id: UUID(), kind: kind, date: Date(), sourceApp: app?.localizedName, sourceBundle: app?.bundleURL?.path, pinned: false, hash: hash)
        }
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            var item = base(.file, Self.digest(urls.map(\.path).joined(separator: "\n")))
            item.filePaths = urls.map(\.path)
            return item
        }
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), data.count < 40_000_000,
           pasteboard.string(forType: .string) == nil,
           let rep = NSBitmapImageRep(data: data), let png = rep.representation(using: .png, properties: [:]) {
            let hash = Self.digest(png)
            var item = base(.image, hash)
            let name = "\(hash.prefix(24)).png"
            try? png.write(to: imageFolder.appendingPathComponent(name))
            item.imageFile = name
            item.imageSize = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
            return item
        }
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let kind: ClipItem.Kind
            if NSColor(hex: trimmed) != nil, trimmed.hasPrefix("#") {
                kind = .color
            } else if let url = URL(string: trimmed), url.scheme?.hasPrefix("http") == true, !trimmed.contains(" ") {
                kind = .link
            } else { kind = .text }
            var item = base(kind, Self.digest(string))
            item.text = string
            return item
        }
        return nil
    }

    private func insert(_ item: ClipItem) {
        var item = item
        // Copying something again moves it to the top and keeps its pin.
        if let existing = items.firstIndex(where: { $0.hash == item.hash }) {
            item.pinned = items[existing].pinned
            items.remove(at: existing)
        }
        items.insert(item, at: 0)
        trim()
        save()
        onChange?()
    }

    private func trim() {
        while items.filter({ !$0.pinned }).count > limit, let index = items.lastIndex(where: { !$0.pinned }) {
            removeFiles(items[index])
            items.remove(at: index)
        }
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        return NSImage(contentsOf: imageFolder.appendingPathComponent(name))
    }

    /// Puts an entry back on the pasteboard.
    func write(_ item: ClipItem, plainText: Bool = false) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        case .file:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            if plainText { pasteboard.setString((item.filePaths ?? []).joined(separator: "\n"), forType: .string) } else { pasteboard.writeObjects(urls) }
        default:
            pasteboard.setString(item.text ?? "", forType: .string)
        }
        // Our own write should not be recorded as a new copy.
        changeCount = pasteboard.changeCount
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
        onChange?()
    }

    func delete(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        removeFiles(items[index])
        items.remove(at: index)
        save()
        onChange?()
    }

    func clear() {
        items.filter { !$0.pinned }.forEach(removeFiles)
        items.removeAll { !$0.pinned }
        save()
        onChange?()
    }

    private func removeFiles(_ item: ClipItem) {
        guard let name = item.imageFile, !items.contains(where: { $0.id != item.id && $0.imageFile == name }) else { return }
        try? FileManager.default.removeItem(at: imageFolder.appendingPathComponent(name))
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyFile) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        items = (try? decoder.decode([ClipItem].self, from: data)) ?? []
    }

    private func save() {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        guard let data = try? encoder.encode(items) else { return }
        try? data.write(to: historyFile, options: .atomic)
        // History can contain sensitive text; keep it readable by this user only.
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: historyFile.path)
    }

    static func digest(_ string: String) -> String { digest(Data(string.utf8)) }
    static func digest(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }
}
